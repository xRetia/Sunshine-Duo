$ErrorActionPreference = 'Stop'
$L = New-Object Text.StringBuilder
function A([string]$line) { [void]$L.AppendLine($line) }

# ============ design ============
# patch at real function entry: jmp hook_pre   (rsp = R, [R] = caller's RA, untouched)
# hook_pre: save ppSessionInfo/pCount ptrs to globals, overwrite [R] with filter addr, jmp real entry
# real function runs with 100% original stack semantics, its ret goes to filter
# filter: patch states, ret to caller's real RA

A '# gv_hook.s - inline-hook wtsapi32!WTSEnumerateSessionsW/A inside GameViewerService'
A '    .text'
A '    .globl DllMain'
A 'DllMain:'
A '    sub $0x28, %rsp'
A '    cmp $1, %edx'
A '    jne .Ldm_ret'
A '    call _install'
A '.Ldm_ret:'
A '    mov $1, %eax'
A '    add $0x28, %rsp'
A '    ret'
A ''
A 'VirtualAllocX:'
A '    sub $0x28, %rsp'
A '    mov %rcx, %rdx'
A '    xor %ecx, %ecx'
A '    mov $0x3000, %r8d'
A '    mov $0x40, %r9d'
A '    call VirtualAlloc'
A '    add $0x28, %rsp'
A '    ret'
A ''

A '_install:'
A '    push %rbx'
A '    push %r12'
A '    push %r13'
A '    push %r14'
A '    push %r15'
A '    sub $0x40, %rsp'
A '    call GetCurrentProcessId'
A '    mov %eax, mypid(%rip)'
A '    call GetCurrentThreadId'
A '    mov %eax, mytid(%rip)'
A '    xor %ecx, %ecx'
A '    mov $1, %edx'
A '    mov $1, %r8d'
A '    lea evname(%rip), %r9'
A '    call CreateEventA'
A '    lea wtsname(%rip), %rcx'
A '    call GetModuleHandleA'
A '    test %rax, %rax'
A '    jnz .Lgot_wts'
A '    lea wtsname(%rip), %rcx'
A '    call LoadLibraryA'
A '    test %rax, %rax'
A '    jz .Linst_fail'
A '.Lgot_wts:'
A '    mov %rax, hWts(%rip)'
A '    mov %rax, %rcx'
A '    lea nW(%rip), %rdx'
A '    call GetProcAddress'
A '    test %rax, %rax'
A '    jz .Linst_fail'
A '    mov %rax, realW(%rip)'
A '    mov hWts(%rip), %rcx'
A '    lea nA(%rip), %rdx'
A '    call GetProcAddress'
A '    test %rax, %rax'
A '    jz .Linst_fail'
A '    mov %rax, realA(%rip)'
A '    cld'
A '    # ---- build trampoline W (copy 16B prologue + jmp realW+16) ----'
A '    mov $64, %ecx'
A '    call VirtualAllocX'
A '    test %rax, %rax'
A '    jz .LfailW'
A '    mov %rax, trampW(%rip)'
A '    mov realW(%rip), %rsi'
A '    mov %rax, %rdi'
A '    mov $16, %ecx'
A '    rep movsb'
A '    mov realW(%rip), %rax'
A '    add $16, %rax'
A '    movw $0xB848, 16(%rdi)'
A '    movq %rax, 18(%rdi)'
A '    movw $0xE0FF, 26(%rdi)'
A '    # ---- patch W (14 bytes at realW) ----'
A '    mov realW(%rip), %rcx'
A '    mov $14, %edx'
A '    mov $0x40, %r8d'
A '    lea oldprot(%rip), %r9'
A '    call VirtualProtect'
A '    test %eax, %eax'
A '    jz .LfailW'
A '    mov realW(%rip), %rdi'
A '    movw $0x25FF, (%rdi)'
A '    movl $0, 2(%rdi)'
A '    lea hook_preW(%rip), %rax'
A '    movq %rax, 6(%rdi)'
A '    mov realW(%rip), %rcx'
A '    mov $14, %edx'
A '    mov oldprot(%rip), %r8d'
A '    lea oldprot(%rip), %r9'
A '    call VirtualProtect'
A '    jmp .LpA'
A '.LfailW:'
A '    xor %ecx, %ecx'
A '    mov $1, %edx'
A '    mov $1, %r8d'
A '    lea errW(%rip), %r9'
A '    call CreateEventA'
A '    jmp .Lresume'
A '    # ---- build trampoline A (copy 18B prologue + jmp realA+18) ----'
A '.LpA:'
A '    mov $64, %ecx'
A '    call VirtualAllocX'
A '    test %rax, %rax'
A '    jz .LfailA'
A '    mov %rax, trampA(%rip)'
A '    mov realA(%rip), %rsi'
A '    mov %rax, %rdi'
A '    mov $18, %ecx'
A '    rep movsb'
A '    mov realA(%rip), %rax'
A '    add $18, %rax'
A '    movw $0xB848, 18(%rdi)'
A '    movq %rax, 20(%rdi)'
A '    movw $0xE0FF, 28(%rdi)'
A '    # ---- patch A (14 bytes at realA) ----'
A '    mov realA(%rip), %rcx'
A '    mov $14, %edx'
A '    mov $0x40, %r8d'
A '    lea oldprot(%rip), %r9'
A '    call VirtualProtect'
A '    test %eax, %eax'
A '    jz .LfailA'
A '    mov realA(%rip), %rdi'
A '    movw $0x25FF, (%rdi)'
A '    movl $0, 2(%rdi)'
A '    lea hook_preA(%rip), %rax'
A '    movq %rax, 6(%rdi)'
A '    mov realA(%rip), %rcx'
A '    mov $14, %edx'
A '    mov oldprot(%rip), %r8d'
A '    lea oldprot(%rip), %r9'
A '    call VirtualProtect'
A '    jmp .Lresume'
A '.LfailA:'
A '    xor %ecx, %ecx'
A '    mov $1, %edx'
A '    mov $1, %r8d'
A '    lea errA(%rip), %r9'
A '    call CreateEventA'
A '    jmp .Lresume'
A '.Lresume:'
A '.Lpop:'
A '    add $0x40, %rsp'
A '    pop %r15'
A '    pop %r14'
A '    pop %r13'
A '    pop %r12'
A '    pop %rbx'
A '    ret'
A '.Linst_fail:'
A '    add $0x40, %rsp'
A '    pop %r15'
A '    pop %r14'
A '    pop %r13'
A '    pop %r12'
A '    pop %rbx'
A '    ret'
A ''

# ---- hook_preW: entered via jmp, rsp = R (original entry semantics), all regs original ----
A 'hook_preW:'
A '    mov (%rsp), %rax'
A '    mov %rax, gv_raW(%rip)'
A '    mov %r9, gv_ppW(%rip)'
A '    mov 0x28(%rsp), %rax'
A '    mov %rax, gv_cntW(%rip)'
A '    lea filterW(%rip), %rax'
A '    movq %rax, (%rsp)'
A '    mov trampW(%rip), %rax'
A '    jmp *%rax'
A ''

A 'hook_preA:'
A '    mov (%rsp), %rax'
A '    mov %rax, gv_raA(%rip)'
A '    mov %r9, gv_ppA(%rip)'
A '    mov 0x28(%rsp), %rax'
A '    mov %rax, gv_cntA(%rip)'
A '    lea filterA(%rip), %rax'
A '    movq %rax, (%rsp)'
A '    mov trampA(%rip), %rax'
A '    jmp *%rax'
A ''

# ---- filterW: entered via ret from real function, rsp = R+8 ----
A 'filterW:'
A '    push %rbx'
A '    push %r12'
A '    sub $0x28, %rsp'
A '    call WTSGetActiveConsoleSessionId'
A '    mov %eax, %r12d'
A '    mov gv_ppW(%rip), %rbx'
A '    mov (%rbx), %rcx'
A '    mov gv_cntW(%rip), %rbx'
A '    mov (%rbx), %rdx'
A '    test %rcx, %rcx'
A '    jz .Lfw_ret'
A '    test %rdx, %rdx'
A '    jz .Lfw_ret'
A '    xor %r8d, %r8d'
A '.Lfw_loop:'
A '    cmp %rdx, %r8'
A '    jae .Lfw_ret'
A '    lea (%r8,%r8,2), %r10'
A '    mov (%rcx,%r10,8), %eax'
A '    cmpl $0, 16(%rcx,%r10,8)'
A '    jne .Lfw_next'
A '    cmp %r12d, %eax'
A '    je .Lfw_next'
A '    movl $4, 16(%rcx,%r10,8)'
A '.Lfw_next:'
A '    inc %r8'
A '    jmp .Lfw_loop'
A '.Lfw_ret:'
A '    add $0x28, %rsp'
A '    pop %r12'
A '    pop %rbx'
A '    jmp *gv_raW(%rip)'
A ''

A 'filterA:'
A '    push %rbx'
A '    push %r12'
A '    sub $0x28, %rsp'
A '    call WTSGetActiveConsoleSessionId'
A '    mov %eax, %r12d'
A '    mov gv_ppA(%rip), %rbx'
A '    mov (%rbx), %rcx'
A '    mov gv_cntA(%rip), %rbx'
A '    mov (%rbx), %rdx'
A '    test %rcx, %rcx'
A '    jz .Lfa_ret'
A '    test %rdx, %rdx'
A '    jz .Lfa_ret'
A '    xor %r8d, %r8d'
A '.Lfa_loop:'
A '    cmp %rdx, %r8'
A '    jae .Lfa_ret'
A '    lea (%r8,%r8,2), %r10'
A '    mov (%rcx,%r10,8), %eax'
A '    cmpl $0, 16(%rcx,%r10,8)'
A '    jne .Lfa_next'
A '    cmp %r12d, %eax'
A '    je .Lfa_next'
A '    movl $4, 16(%rcx,%r10,8)'
A '.Lfa_next:'
A '    inc %r8'
A '    jmp .Lfa_loop'
A '.Lfa_ret:'
A '    add $0x28, %rsp'
A '    pop %r12'
A '    pop %rbx'
A '    jmp *gv_raA(%rip)'
A ''

A '    .data'
A '    .align 8'
A 'hWts:    .quad 0'
A 'realW:   .quad 0'
A 'realA:   .quad 0'
A 'oldprot: .quad 0'
A 'trampW:  .quad 0'
A 'trampA:  .quad 0'
A 'gv_ppW:  .quad 0'
A 'gv_cntW: .quad 0'
A 'gv_raW:  .quad 0'
A 'gv_ppA:  .quad 0'
A 'gv_cntA: .quad 0'
A 'gv_raA:  .quad 0'
A 'mypid:   .long 0'
A 'mytid:   .long 0'
A '    .align 8'
A 'evname:  .asciz "Global\\gv_hook_injected"'
A 'wtsname: .asciz "wtsapi32.dll"'
A 'nW:      .asciz "WTSEnumerateSessionsW"'
A 'nA:      .asciz "WTSEnumerateSessionsA"'
A 'errW:    .asciz "Global\\gv_err_patchW"'
A 'errA:    .asciz "Global\\gv_err_patchA"'
A '    .align 8'
A 'te32:    .space 64'

Set-Content -LiteralPath '.temp\gv_hook.s' -Value $L.ToString() -Encoding ASCII
Write-Output ("generated lines: " + ($L.ToString() -split "`n").Count)
& 'C:\Komandare\Unixlike\bin\as.exe' -o '.temp\gv_hook.o' '.temp\gv_hook.s'
Write-Output ("as exit: " + $LASTEXITCODE)
& 'C:\Komandare\Unixlike\bin\ld.exe' -m i386pep --dll -e DllMain --export-all-symbols -o '.temp\gv_hook.dll' '.temp\gv_hook.o' 'C:\Windows\System32\kernel32.dll'
Write-Output ("ld exit: " + $LASTEXITCODE)
